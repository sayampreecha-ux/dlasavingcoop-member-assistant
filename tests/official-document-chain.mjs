import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {documentChain}=require('../scripts/official-freshness.js');
const doc=(id,extra={})=>({id,type:'ANNOUNCEMENT',title:'ประกาศ',originalUrl:'https://www.dlasavingcoop.com/show.php?No='+id,effectiveDate:'2026-07-01',review:{primaryVerified:true},...extra});
const original=doc('4865');
const amend=doc('4893',{amendsDocumentIds:['4865']});
const extend=doc('5000',{extendsDocumentIds:['4893'],effectiveDate:'2026-09-29'});
const cancel=doc('5001',{cancelsDocumentIds:['5000'],effectiveDate:'2026-09-30'});
const replaced=doc('5002',{replacesDocumentIds:['5001'],effectiveDate:'2026-10-01'});
const chain=documentChain({documents:[original,amend,extend,cancel,replaced]},'4865','2026-10-22');
assert.deepEqual([...chain.documentIds].sort(),['4865','4893','5000','5001','5002'].sort());
assert.equal(chain.decision,'EVIDENCE_LOCK');
assert.equal(chain.verified,false);
assert.ok(chain.issues.includes('LATEST_INDEX_COVERAGE_UNVERIFIED'));
const missing=documentChain({documents:[original,doc('4893',{amendsDocumentIds:['4865','404']})]},'4865','2026-10-22');
assert.ok(missing.missingDocumentIds.includes('404'));
assert.ok(missing.issues.includes('MISSING_REFERENCED_DOCUMENT'));
const conflict=documentChain({documents:[original,doc('4893',{conflictsWithDocumentIds:['4865']})]},'4865','2026-10-22');
assert.ok(conflict.issues.includes('CONFLICTING_DOCUMENTS'));
const noDate=documentChain({documents:[doc('4865',{effectiveDate:null})]},'4865','2026-10-22');
assert.ok(noDate.issues.includes('EFFECTIVE_DATE_UNVERIFIED'));
const unverified=documentChain({documents:[doc('4865',{review:{primaryVerified:false}})]},'4865','2026-10-22');
assert.ok(unverified.issues.includes('PRIMARY_NOT_VERIFIED'));
const unknown=documentChain({documents:[original]},'9999','2026-10-22');
assert.ok(unknown.issues.includes('ROOT_DOCUMENT_MISSING'));
assert.deepEqual(unknown.missingDocumentIds,['9999']);
console.log('OFFICIAL DOCUMENT CHAIN: amendment, extension, cancellation, replacement, missing reference, conflict, missing date and unverified primary PASS');
