import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const start=html.indexOf('function selectTrackingNotices(');
const end=html.indexOf("function render(r,input='')",start);
assert.ok(start>=0&&end>start,'execute the production filter');
const context=vm.createContext({});
vm.runInContext(html.slice(start,end),context);
const select=(input,data)=>Array.from(context.selectTrackingNotices(data,input),e=>e.id);
const approved={id:'approved',title:'ผู้ที่ได้รับความเห็นชอบให้เป็นสมาชิกสหกรณ์ (ไม่เคยเป็นสมาชิก)',summary:'เปิดตรวจผลจากประกาศทางการ',sourceState:'DIRECT_VERIFIED',directSourceUrl:'https://www.dlasavingcoop.com/show.php?No=4936'};
const record=(id,title,extra={})=>({...approved,id,title,directSourceUrl:'https://www.dlasavingcoop.com/show.php?No='+id,...extra});
const incomplete=record('100','รายชื่อผู้สมัครสมาชิกส่งเอกสารมาไม่ครบ');
const round=record('101','กำหนดรอบรับสมัครสมาชิกใหม่');
const welfare=record('102','ผลการพิจารณาอนุมัติสวัสดิการสมาชิก');
const loan=record('103','แจ้งผลอนุมัติเงินกู้');
const cremation=record('104','ผลการอนุมัติสมาชิกสมาคมฌาปนกิจสงเคราะห์');
const former=record('105','ผู้ที่ได้รับความเห็นชอบให้เป็นสมาชิกสหกรณ์ (เคยเป็นสมาชิก)');
const data={trackingNotices:[approved,former,incomplete,round,welfare,loan,cremation],events:[approved]};
for(const query of ['ผลอนุมัติสมัครสมาชิก','ติดตามผลอนุมัติสมัครสมาชิก','ผลอนุมัติสมาชิก','ติดตามผลอนุมัติสมาชิก'])assert.deepEqual(select(query,data),['approved','105'],query);
const loanForMembers=record('4946','ผลการอนุมัติเงินให้กู้แก่สมาชิก (ตัดรอบเอกสารวันที่ 15 ต.ค. 69)',{category:'membership'});
const resigned=record('4944','[ผลการอนุมัติ] สมาชิกพ้นจากสมาชิกภาพ (กรณีสมาชิกลาออก)',{category:'membership'});
for(const query of ['ผลอนุมัติสมัครสมาชิก','ผลอนุมัติสมาชิก'])assert.deepEqual(select(query,{approvalIndex:[loanForMembers,resigned,approved,former],trackingNotices:[]}),['approved','105'],'ignore loans and resignations while preserving member approvals');
assert.deepEqual(select('เอกสารสมัครสมาชิก',data),['100']);
assert.deepEqual(select('รอบสมาชิก',data),['100','101'],'preserve existing round results without introducing approvals');
// Preserve the existing welfare category's inclusion of สงเคราะห์ notices.
for(const [query,ids]of [['ผลอนุมัติเงินกู้',['103']],['ผลอนุมัติสวัสดิการ',['102','104']],['ผลอนุมัติฌาปนกิจ',['104']]])assert.deepEqual(select(query,data),ids,query);
for(const extra of [{sourceState:'UNVERIFIED'},{directSourceUrl:null},{expiresAt:'2000-01-01T00:00:00Z'}])assert.deepEqual(select('ผลอนุมัติสมัครสมาชิก',{events:[{...approved,...extra}]}),[]);
assert.deepEqual(select('ผลอนุมัติสมัครสมาชิก',{events:[{...approved,expiresAt:'2099-01-01T00:00:00Z'}]}),['approved']);
assert.deepEqual(select('ผลอนุมัติสมัครสมาชิก',{}),[]);
const feed=JSON.parse(fs.readFileSync(new URL('../data/current-events.json',import.meta.url)));
const ids=select('ผลอนุมัติสมัครสมาชิก',feed);
assert.ok(ids.includes('official-4937')&&ids.includes('official-4936'),'both September approved-member originals appear');
assert.equal(new Set(ids).size,ids.length);
console.log('MEMBER TRACKING RUNTIME: approval titles, category isolation, expiry, evidence, deduplication and real feed PASS');
