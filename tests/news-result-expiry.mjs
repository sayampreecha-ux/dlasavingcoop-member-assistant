import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const code=fs.readFileSync(new URL('../scripts/update-current-events.mjs',import.meta.url),'utf8');
let body='';
const ctx={URL,Date,Intl,fetch:async()=>({ok:true,text:async()=>body})};
vm.createContext(ctx);
vm.runInContext(code.slice(code.indexOf('const TH_MONTHS'),code.indexOf('const now=new Date();')),ctx);
const item={id:'synthetic',title:'[ผลการอนุมัติ] สมาชิกพ้นจากสมาชิกภาพ',score:68,url:'https://www.dlasavingcoop.com/show.php?No=900001',source:'official-notice',publishedAt:'2026-10-21T09:00:00.000Z'};
body='<p>เมื่อวันที่ 15 ตุลาคม 2569</p>';
let result=await ctx.enrich(item);
assert.equal(result.eventDate,'2026-10-15');
assert.equal(result.expiresAt,null,'past approval must not expire a newly published result');
assert.equal(result.publishedAt,item.publishedAt);
body='<p>ส่งคำร้องภายในวันที่ 15 ตุลาคม 2569</p>';
result=await ctx.enrich(item);
assert.equal(result.expiresAt,'2026-10-15T17:00:00.000Z','explicit result deadline must still expire');
body='<p>วันที่ 15 ตุลาคม 2569</p>';
result=await ctx.enrich({...item,title:'ขอเชิญประชุมใหญ่สามัญ'});
assert.equal(result.expiresAt,'2026-10-15T17:00:00.000Z','meeting expiry remains unchanged');
console.log('NEWS RESULT EXPIRY: 3 scenarios PASS');
